// 左右反転・転置で作るもの
function mirrorH(rows) { return rows.map(r => r.split('').reverse().join('')); }
function transpose(rows) {
  const out = [];
  for (let x = 0; x < 12; x++) { let s = ''; for (let y = 0; y < 12; y++) s += rows[y][x]; out.push(s); }
  return out;
}
ICON_SRC.redo   = mirrorH(ICON_SRC.undo);
ICON_SRC.rotccw = mirrorH(ICON_SRC.rotcw);
ICON_SRC.flipv  = transpose(ICON_SRC.fliph);

const ICON_URL = {};
(function buildIcons() {
  const c = document.createElement('canvas');
  c.width = 12; c.height = 12;
  const g = c.getContext('2d');
  for (const [name, rows] of Object.entries(ICON_SRC)) {
    g.clearRect(0, 0, 12, 12);
    g.fillStyle = '#fff';
    rows.forEach((r, y) => { for (let x = 0; x < 12; x++) if (r[x] === '#') g.fillRect(x, y, 1, 1); });
    ICON_URL[name] = c.toDataURL('image/png');
  }
})();

export function setIcon(btn, name) {
  let s = btn.querySelector('.ic');
  if (!s) { s = document.createElement('span'); s.className = 'ic'; btn.appendChild(s); }
  const u = `url(${ICON_URL[name]})`;
  s.style.webkitMaskImage = u;
  s.style.maskImage = u;
}
