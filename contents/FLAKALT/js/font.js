GLYPHS.set('▒', shade(2)); // ▒
GLYPHS.set('▓', shade(3)); // ▓
GLYPHS.set('█', shade(4)); // █

const MISSING = (() => {
  const g = blank();
  hSpan(g, 0, 0, 4);
  hSpan(g, 6, 0, 4);
  vSpan(g, 0, 0, 6);
  vSpan(g, 4, 0, 6);
  return g;
})();

export const FONT_W = CELL_W;
export const FONT_H = CELL_H;

/* 小文字は大文字にまとめる。DOS の画面は基本ぜんぶ大文字なので困らない。 */
export function glyphFor(ch) {
  let g = GLYPHS.get(ch);
  if (g) return g;
  g = GLYPHS.get(ch.toUpperCase());
  return g || MISSING;
}
