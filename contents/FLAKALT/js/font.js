/* 罫線・網掛けはコードで作る。手で打つと繋ぎ目を間違えるので。 */
const CELL_W = 6;
const CELL_H = 8;
const V_COL = 2;   // 単線の縦位置
const H_ROW = 3;   // 単線の横位置
const V_COL2 = [1, 3]; // 二重線の縦位置
const H_ROW2 = [2, 4]; // 二重線の横位置

function blank() {
  return new Uint8Array(CELL_H);
}

function setPx(g, col, row) {
  if (col < 0 || col >= CELL_W || row < 0 || row >= CELL_H) return;
  g[row] |= 1 << (CELL_W - 1 - col);
}

function hSpan(g, row, c0, c1) {
  for (let c = c0; c <= c1; c++) setPx(g, c, row);
}

function vSpan(g, col, r0, r1) {
  for (let r = r0; r <= r1; r++) setPx(g, col, r);
}

/* 単線の罫線。上下左右どの腕が生えているかで作る。 */
function singleBox(up, down, left, right) {
  const g = blank();
  if (up) vSpan(g, V_COL, 0, H_ROW);
  if (down) vSpan(g, V_COL, H_ROW, CELL_H - 1);
  if (left) hSpan(g, H_ROW, 0, V_COL);
  if (right) hSpan(g, H_ROW, V_COL, CELL_W - 1);
  return g;
}

/* 網掛け。ディザの濃さ違い。 */
function shade(kind) {
  const g = blank();
  for (let r = 0; r < CELL_H; r++) {
    for (let c = 0; c < CELL_W; c++) {
      let on;
      if (kind === 4) on = true;                       // █
      else if (kind === 3) on = !((r & 1) && (c & 1)); // ▓
      else if (kind === 2) on = ((r + c) & 1) === 0;   // ▒
      else on = ((r & 1) === 0) && ((c & 1) === 0);    // ░
      if (on) setPx(g, c, r);
    }
  }
  return g;
}

const GLYPHS = new Map();

/* 英数字を 6x8 セルへ展開 */
for (const [ch, art] of Object.entries(ASCII)) {
  const rows = art.split('/');
  const g = blank();
  for (let r = 0; r < rows.length; r++) {
    const line = rows[r];
    for (let c = 0; c < line.length; c++) {
      if (line[c] === '#') setPx(g, c, r);
    }
  }
  GLYPHS.set(ch, g);
}

