/* ============================================================
   FLAKALT — models.js
   ワイヤーフレームのメッシュ定義。

   面は持たない。頂点と稜線だけ。隠面消去もしない（ワイヤーフレームは
   裏側の線が透けて見えるほうがそれらしい）。
   ローカル座標は +Z が機首方向、+Y が上、+X が右。
   ============================================================ */

/* mesh = { v: [[x,y,z]...], e: [[i,j]...], r: 当たり判定半径(ローカル) } */

function mesh(v, e) {
  let r = 0;
  for (const p of v) r = Math.max(r, Math.hypot(p[0], p[1], p[2]));
  return { v, e, r };
}

